// Assembles README.md from body.md (the prose; edit that file, never README.md),
// the hero panel and items.json, then checks the result.
import fs from 'node:fs';
import path from 'node:path';
import { FACTS, ROOT } from './facts.mjs';
import { ALT, OUT_DIR } from './panels.mjs';

export const MARKER = '<!-- generated by tools/readme/build.mjs from tools/readme/body.md. do not edit by hand. -->';

const PLATFORM_FOR = {
  x64: 'Intel and AMD 64-bit PCs (most PCs)',
  arm64: 'Windows on ARM',
  x86: '32-bit Windows only',
};
const PLATFORM_ORDER = ['x64', 'arm64', 'x86'];

const HERE = path.join(ROOT, 'tools', 'readme');
const items = JSON.parse(fs.readFileSync(path.join(HERE, 'items.json'), 'utf8'));
const escAttr = s => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

// GitHub repo pages drop <source> variants from a <picture> inside <a>, so the
// picture stays bare (verify() fails the build if one gets wrapped).
function pic(base, alt) {
  return `<picture>
<source media="(max-width: 500px) and (prefers-color-scheme: dark)" srcset="${OUT_DIR}/${base}-narrow-dark.svg">
<source media="(max-width: 500px)" srcset="${OUT_DIR}/${base}-narrow-light.svg">
<source media="(prefers-color-scheme: dark)" srcset="${OUT_DIR}/${base}-dark.svg">
<img alt="${escAttr(alt)}" src="${OUT_DIR}/${base}-light.svg" width="100%">
</picture>`;
}

function installers() {
  const missing = FACTS.platforms.filter(p => !PLATFORM_FOR[p]);
  if (missing.length) throw new Error(`readme: no installer description for ${missing.join(', ')}`);
  const rows = PLATFORM_ORDER.filter(p => FACTS.platforms.includes(p))
    .concat(FACTS.platforms.filter(p => !PLATFORM_ORDER.includes(p)))
    .map(p => `| \`SecureWall_${p}.msi\` | ${PLATFORM_FOR[p]} |`);
  return ['| Installer | For |', '|---|---|', ...rows].join('\n');
}

function docs() {
  return items.map(it => `- [${it.path}](${it.path}): ${it.what}`).join('\n');
}

export function render() {
  const body = fs.readFileSync(path.join(HERE, 'body.md'), 'utf8').replace(/\r\n/g, '\n');
  const tokens = {
    hero: pic('hero', ALT),
    installers: installers(),
    docs: docs(),
    upstream_release: FACTS.upstream.release,
    upstream_commit: FACTS.upstream.commit,
  };
  const md = body.replace(/\{\{(\w+)\}\}/g, (m, k) => {
    if (!(k in tokens)) throw new Error(`readme: unknown token ${m}`);
    return tokens[k];
  });
  return `${MARKER}\n${md}`;
}

export function verify(md, files = {}) {
  let bad = 0;
  const fail = msg => { console.error(`FAIL README: ${msg}`); bad++; };
  if (!md.startsWith(MARKER + '\n')) fail('generated marker is not the first line');
  if (/\{\{\w+\}\}/.test(md)) fail('unreplaced token');
  for (const h of ['## Install', '## When an app is blocked', '## Build and test', '## Lineage and license']) {
    if (!md.includes(`\n${h}\n`)) fail(`section "${h}" missing`);
  }
  for (const link of ['https://secwall.org/', 'docs/INSTALL.md', 'LICENSE', 'docs/SECURITY.md']) {
    if (!md.includes(`](${link})`)) fail(`link to ${link} missing`);
  }
  if (!md.includes('```powershell\ndotnet run --project tests')) fail('build command missing');
  for (const p of FACTS.platforms) if (!md.includes(`SecureWall_${p}.msi`)) fail(`installer ${p} missing`);

  // Every image the README references exists (in this build's output or on disk).
  for (const m of md.matchAll(/(?:src|srcset)="([^"]+)"/g)) {
    if (!(m[1] in files) && !existsExact(m[1])) fail(`missing asset ${m[1]}`);
  }
  if (/<a\b[^>]*>\s*<picture/.test(md)) fail('a <picture> is wrapped in a link');

  // Every documentation item is listed exactly once in its section.
  const start = md.indexOf('\n## Documentation\n');
  if (start < 0) fail('section "## Documentation" missing');
  const end = md.indexOf('\n## ', start + 1);
  const list = md.slice(start, end < 0 ? undefined : end);
  for (const it of items) {
    const hits = list.split(`](${it.path})`).length - 1;
    if (hits !== 1) fail(`${it.path} linked ${hits} times in the documentation list`);
  }

  // Local link targets exist. Remote links are checked by meta.mjs --check after merge.
  for (const m of md.matchAll(/\]\(<?([^)\s>]+)>?(?:\s+"[^"]*")?\)/g)) {
    const target = m[1];
    if (/^[a-z]+:/i.test(target) || target.startsWith('#')) continue;
    if (!existsExact(target.split('#')[0])) fail(`broken local link ${target}`);
  }
  return bad;
}

// GitHub paths are case-sensitive; Windows and macOS disks are not, so
// fs.existsSync alone would pass docs/install.md for docs/INSTALL.md.
function existsExact(rel) {
  let dir = ROOT;
  for (const part of rel.split('/').filter(Boolean)) {
    if (!fs.existsSync(dir) || !fs.statSync(dir).isDirectory()) return false;
    if (!fs.readdirSync(dir).includes(part)) return false;
    dir = path.join(dir, part);
  }
  return true;
}
